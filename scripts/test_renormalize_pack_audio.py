#!/usr/bin/env python3
"""Tests for scripts/renormalize_pack_audio.py (stdlib only, no network).

Pins the enforceable contract: a quiet asset gets the generate-pack-audio
gain applied in place and its manifest row rewritten (sha256, bytes, notes
recording the gain) while every untouched line stays byte-identical; an
already-conforming asset is not rewritten; a second run over changed bytes
is a no-op (idempotence); an id the manifest does not name is refused
without touching anything; a row whose file is missing is refused; a file
the DSP cannot read (non-16-bit) fails loudly and stays alone; and
--all-tracked normalizes exactly the git-tracked media, never the
gitignored bulk file. Fixtures are synthetic 16-bit PCM built here.

Run: python3 -m unittest scripts.test_renormalize_pack_audio -v
"""

import hashlib
import json
import math
import shutil
import struct
import subprocess
import sys
import tempfile
import unittest
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "renormalize_pack_audio.py"

RATE = 8000
# TARGET_ACTIVE_RMS * 32767 * sqrt(2): the sine peak whose active RMS sits
# exactly on the target, i.e. an already-conforming amplitude.
CONFORMING_PEAK = round(0.15 * 32767 * math.sqrt(2))


def write_wav(path: Path, peak: int, seconds: float = 0.6, silence: float = 0.1):
    """16-bit mono sine burst padded with silence (speech-like envelope)."""
    n = int(RATE * seconds)
    lead = int(RATE * silence)
    frames = bytearray()
    for i in range(n):
        amp = peak if lead <= i < n - lead else 0
        frames += struct.pack("<h", int(amp * math.sin(2 * math.pi * 440 * i / RATE)))
    with wave.open(str(path), "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(RATE)
        wav.writeframes(bytes(frames))


def write_wav8(path: Path) -> None:
    """8-bit PCM file the DSP refuses (sampwidth != 2)."""
    with wave.open(str(path), "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(1)
        wav.setframerate(RATE)
        wav.writeframes(bytes([128, 200] * 100))


def make_row(aid: str, pack: Path) -> dict:
    path = pack / "media" / f"{aid}.wav"
    with wave.open(str(path)) as wav:
        rate, channels, frames = wav.getframerate(), wav.getnchannels(), wav.getnframes()
    return {
        "id": aid,
        "file": f"media/{aid}.wav",
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "bytes": path.stat().st_size,
        "sample_rate": rate,
        "channels": channels,
        "seconds": round(frames / rate, 3),
        "provenance": "model-output",
        "synthesizer": {"runtime": "qwen3-tts", "model": "test", "voice": "v"},
        "text": "テスト",
        "generated": "2026-10-14",
        "notes": "generated by scripts/generate-pack-audio.py; AI output, "
                 "not a human recording and not human-reviewed",
    }


def make_pack(tmp: Path) -> Path:
    """Pack fixture: quiet + conforming assets, rows describing the bytes."""
    pack = tmp / "languages" / "test-pack"
    (pack / "media").mkdir(parents=True)
    write_wav(pack / "media" / "t.quiet.wav", peak=1000)
    write_wav(pack / "media" / "t.conform.wav", peak=CONFORMING_PEAK)
    rows = [make_row("t.conform", pack), make_row("t.quiet", pack)]
    (pack / "media" / "manifest.jsonl").write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    return pack


def run(pack: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(SCRIPT), str(pack), *args],
        capture_output=True, text=True)


def manifest_lines(pack: Path) -> dict[str, str]:
    return {json.loads(l)["id"]: l
            for l in (pack / "media" / "manifest.jsonl").read_text().splitlines(True)}


def row_of(pack: Path, aid: str) -> dict:
    return json.loads(manifest_lines(pack)[aid])


def make_row_stub(aid: str) -> dict:
    """Row naming a file that is not on disk (refusal fixture)."""
    return {"id": aid, "file": f"media/{aid}.wav", "sha256": "0" * 64,
            "bytes": 0, "sample_rate": RATE, "channels": 1, "seconds": 0.0,
            "provenance": "model-output", "synthesizer": {"runtime": "x"},
            "text": "x", "generated": "2026-10-14", "notes": "stub"}


class RenormalizeTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = Path(self._tmp.name)
        self.pack = make_pack(self.tmp)

    def tearDown(self):
        self._tmp.cleanup()

    def test_quiet_asset_gets_gain_and_row_updated(self):
        wav = self.pack / "media" / "t.quiet.wav"
        before_bytes = wav.read_bytes()
        r = run(self.pack, "t.quiet")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn(f"summary {self.pack}: rows updated=1 rows unchanged=0 "
                      "rows failing=0", r.stderr)
        self.assertNotEqual(wav.read_bytes(), before_bytes)
        row = row_of(self.pack, "t.quiet")
        self.assertEqual(row["sha256"], hashlib.sha256(wav.read_bytes()).hexdigest())
        self.assertEqual(row["bytes"], wav.stat().st_size)
        self.assertIn("loudness normalized, gain", row["notes"])
        self.assertIn("AI output, not a human recording", row["notes"])
        self.assertEqual(row["text"], "テスト")  # schema/keys preserved
        self.assertEqual(
            list(row),
            ["id", "file", "sha256", "bytes", "sample_rate", "channels",
             "seconds", "provenance", "synthesizer", "text", "generated", "notes"])

    def test_row_of_untouched_asset_byte_identical(self):
        before = manifest_lines(self.pack)
        run(self.pack, "t.quiet")
        after = manifest_lines(self.pack)
        self.assertEqual(after["t.conform"], before["t.conform"])
        self.assertNotEqual(after["t.quiet"], before["t.quiet"])

    def test_conforming_asset_untouched(self):
        wav = self.pack / "media" / "t.conform.wav"
        before_wav = wav.read_bytes()
        before_manifest = (self.pack / "media" / "manifest.jsonl").read_bytes()
        r = run(self.pack, "t.conform")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("rows updated=0 rows unchanged=1 rows failing=0", r.stderr)
        self.assertEqual(wav.read_bytes(), before_wav)
        self.assertEqual((self.pack / "media" / "manifest.jsonl").read_bytes(),
                         before_manifest)

    def test_second_run_is_noop(self):
        first = run(self.pack, "t.quiet", "t.conform")
        self.assertEqual(first.returncode, 0, first.stderr)
        self.assertIn("rows updated=1 rows unchanged=1 rows failing=0", first.stderr)
        wav_bytes = (self.pack / "media" / "t.quiet.wav").read_bytes()
        manifest = (self.pack / "media" / "manifest.jsonl").read_bytes()
        second = run(self.pack, "t.quiet", "t.conform")
        self.assertEqual(second.returncode, 0, second.stderr)
        self.assertIn("rows updated=0 rows unchanged=2 rows failing=0", second.stderr)
        self.assertEqual((self.pack / "media" / "t.quiet.wav").read_bytes(), wav_bytes)
        self.assertEqual((self.pack / "media" / "manifest.jsonl").read_bytes(), manifest)

    def test_unknown_id_refused_nothing_written(self):
        manifest = (self.pack / "media" / "manifest.jsonl").read_bytes()
        wavs = {p: p.read_bytes() for p in (self.pack / "media").glob("*.wav")}
        r = run(self.pack, "t.nope")
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("refusing", r.stderr)
        self.assertIn("t.nope", r.stderr)
        self.assertEqual((self.pack / "media" / "manifest.jsonl").read_bytes(), manifest)
        for p, b in wavs.items():
            self.assertEqual(p.read_bytes(), b)

    def test_missing_file_refused(self):
        manifest = self.pack / "media" / "manifest.jsonl"
        manifest.write_text(manifest.read_text()
                            + json.dumps(make_row_stub("t.ghost")) + "\n")
        before = manifest.read_bytes()
        r = run(self.pack, "t.ghost")
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("refusing", r.stderr)
        self.assertIn("t.ghost", r.stderr)
        self.assertEqual(manifest.read_bytes(), before)

    def test_unsupported_format_fails_and_stays_alone(self):
        wav = self.pack / "media" / "t.wide8.wav"
        write_wav8(wav)
        manifest = self.pack / "media" / "manifest.jsonl"
        manifest.write_text(manifest.read_text()
                            + json.dumps(make_row("t.wide8", self.pack),
                                         ensure_ascii=False) + "\n")
        before = wav.read_bytes()
        r = run(self.pack, "t.wide8")
        self.assertEqual(r.returncode, 1)
        self.assertIn("rows failing=1", r.stderr)
        self.assertEqual(wav.read_bytes(), before)

    def test_all_tracked_skips_gitignored_bulk(self):
        if shutil.which("git") is None:
            self.skipTest("git not available")
        subprocess.run(["git", "init", "-q", str(self.pack)], check=True)
        bulk = self.pack / "media" / "t.bulk.wav"
        write_wav(bulk, peak=900)
        manifest = self.pack / "media" / "manifest.jsonl"
        manifest.write_text(manifest.read_text()
                            + json.dumps(make_row("t.bulk", self.pack),
                                         ensure_ascii=False) + "\n")
        subprocess.run(["git", "-C", str(self.pack), "add", "--",
                        "media/t.quiet.wav", "media/t.conform.wav",
                        "media/manifest.jsonl"], check=True)
        bulk_before = bulk.read_bytes()
        r = run(self.pack, "--all-tracked")
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn("rows updated=1 rows unchanged=1 rows failing=0", r.stderr)
        self.assertEqual(bulk.read_bytes(), bulk_before)


if __name__ == "__main__":
    unittest.main()
